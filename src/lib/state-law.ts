/** Justia's free copy of each state's code, for checking a citation. */
export function statutesUrl(name: string) {
  const slug = name === "District of Columbia" ? "district-of-columbia" : name.toLowerCase().replace(/\s+/g, "-");
  return `https://law.justia.com/codes/${slug}/`;
}

/** Plain-text summary used as reference material for the AI when it drafts forms for a state. */
export function stateLawSummary(code: string) {
  const s = stateLaw(code);
  if (!s) return null;
  return [
    `Security deposit: max ${s.deposit.max}; return within ${s.deposit.returnBy} (${s.deposit.cite}).`,
    `Late fees: ${s.lateFee.rule}; grace: ${s.lateFee.grace} (${s.lateFee.cite}).`,
    `Nonpayment notice: ${s.nonpayment.text} (${s.nonpayment.cite}).`,
    `Ending month-to-month: landlord ${s.monthToMonth.landlord}; tenant ${s.monthToMonth.tenant} (${s.monthToMonth.cite}).`,
    `Landlord entry: ${s.entry.text} (${s.entry.cite}).`,
    `Voucher / source of income: ${s.soi.text}${s.soi.cite ? ` (${s.soi.cite})` : ""}.`,
    ...(s.notes ?? []),
  ].join("\n");
}
